#!/usr/bin/env python3
"""Generate configuration headers from 06_reconstruction/config_options.tsv
(plan section 22 / 22.1, design 3-4).

  gen_config_headers.py [--check]
  gen_config_headers.py --arch m68k [--check]

--arch m68k (plan 434, D068): the m68k overrides in
06_reconstruction/config_options-m68k.tsv (values that differ from the x86
table or are not in it) are written to 07_kernel/v183.34/m68k/generated/, one
header per row group; no meta_features.h (the m68k build uses the x86 one).
The effective m68k configuration is the x86 table plus these overrides.

Writes 07_kernel/generated/<header> as one '#define MACRO value' line per
option (the observed output form of a Mach 'config'; no config code is
copied), and meta_features.h importing every generated header (hypothesis
H-meta, plan 22.1).  Values whose status is not 'hypothesis' or 'confirmed'
are refused, 'undetermined' rows are skipped.  --check compares the files on disk with what would be written.
"""
import csv, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
TABLE = os.path.join(REPO, '06_reconstruction', 'config_options.tsv')
OUT = os.path.join(REPO, '07_kernel', 'generated')
ARCH = {'m68k': (os.path.join(REPO, '06_reconstruction', 'config_options-m68k.tsv'),
                 os.path.join(REPO, '07_kernel', 'v183.34', 'm68k', 'generated'))}   # plan 434


def render(table=TABLE, with_meta=True):
    rows = list(csv.DictReader(open(table), delimiter='\t'))
    files = {}
    for r in rows:
        if r['status'] == 'undetermined':
            continue                     # not generated (plan 23 design 6)
        if r['status'] not in ('hypothesis', 'confirmed'):
            sys.exit('option %s has status %r' % (r['option'], r['status']))
        if r['macro'] == '-' and r['value'] == '-':
            files.setdefault(r['header'], [])   # header that must exist but defines nothing (plan 140.1)
            continue
        if not r['value'].isdigit():
            sys.exit('option %s value %r is not a number' % (r['option'], r['value']))
        files.setdefault(r['header'], []).append('#define %s %s\n' % (r['macro'], r['value']))
    if not with_meta:
        return {h: ''.join(v) for h, v in files.items()}
    meta = ['/* Generated by 10_tools/reconstruction/gen_config_headers.py from\n',
            ' * 06_reconstruction/config_options.tsv; content is hypothesis H-meta\n',
            ' * (02_plan/RECONSTRUCTION_PLAN.md section 22.1). */\n']
    meta += ['#import <%s>\n' % h for h in sorted(files)]
    files['meta_features.h'] = meta
    return {h: ''.join(v) for h, v in files.items()}


def main():
    args = sys.argv[1:]
    out = OUT
    if '--arch' in args:                 # plan 434
        i = args.index('--arch')
        if i + 1 >= len(args) or args[i + 1] not in ARCH:
            sys.exit('gen_config_headers: --arch takes one of %s' % ', '.join(sorted(ARCH)))
        table, out = ARCH[args[i + 1]]
        del args[i:i + 2]
        want = render(table, with_meta=False)
    else:
        want = render()
    if [a for a in args if a != '--check']:
        sys.exit(__doc__)
    check = '--check' in args
    bad = 0
    for h, text in sorted(want.items()):
        p = os.path.join(out, h)
        if check:
            have = open(p).read() if os.path.exists(p) else None
            if have != text:
                print('DIFF', h)
                bad += 1
        else:
            with open(p, 'w') as o:
                o.write(text)
            print('wrote', os.path.relpath(p, REPO))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
