void DoKbdRepeat()
{
    if ((downCount != -1) && eventsOpen)
    {
	downCount--;
	if (downCount == 0)
	{
	    if (curMapping->keyBits[downKey] & CHARGENMASK)
		DoCharGen(curMapping, downKey, 2);
	    downCount = keyRepeat;
	}
    }
}

