int SetCurBrightness(int level)
{
    short i;

    level = MAX(level, BRIGHT_MIN);
    level = MIN(level, BRIGHT_MAX);

    if (evOpenCalled)	/* plan 729 (D024, D164) */
	for (i=screens-1; i!=-1; i--)
	    evdispatch(4, i, level);
    else
	vidSetBrightness( level );
    return(level);
}

void DoAutoDim()
{
    if (dimmedBrightness < curBright)	/* plan 729 (D024, D164) */
	SetCurBrightness(dimmedBrightness);
    autoDimmed = 1;
}

void UndoAutoDim()
{
    SetCurBrightness(curBright);
    autoDimTime = evg->VertRetraceClock + autoDimPeriod;
    autoDimmed = 0;
}

