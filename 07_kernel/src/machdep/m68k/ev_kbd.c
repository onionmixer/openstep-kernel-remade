void CalcModBit(KeyMapping *map, int bit)
{
	int		bitMask;
	int		myFlags;
	int		oldAlphaLock;

	oldAlphaLock = alphaLock;	/* plan 729 (D024, D164) */
	bitMask = 1<<(bit+16);
	/* Initially clear bit */
	myFlags = evg->eventFlags & (~bitMask);
	if (ModKeysDown(map, bit))
	    myFlags |= bitMask;
	/* If this was the shift bit... */
	if (bit == 1)
	{
		if (myFlags & NX_COMMANDMASK)
		    if (map->modDefs[0] == NULL)	/* plan 729 (D024, D164) */
		    {
			if (myFlags&bitMask)
			{
			    keyPressed = 0;
			}
			else
			    if (!keyPressed)
				alphaLock = !alphaLock;
		    }
		/* And in any case, reset the alphaLock/shift bit */
		myFlags = (myFlags & ~NX_ALPHASHIFTMASK) |
			(alphaLock<<16) | ((myFlags & NX_SHIFTMASK)>>1);
	}
	else if (bit == 0)	/* plan 729 (D024, D164) */
	    alphaLock = (myFlags >> 16) & 1;
	if (oldAlphaLock != alphaLock)	/* plan 729 (D024, D164) */
	    AlphaLockFeedback(alphaLock);
	evg->eventFlags = myFlags;
}

void DoModCalc(KeyMapping *map, int key)
{
    int thisBits;
    NXEventData outData;

    thisBits = map->keyBits[key];
    if (thisBits & MODMASK)
    {
	CalcModBit(map,thisBits & WHICHMODMASK);
	/* The driver generates flags-changed events only when there is
	   no key-down or key-up event generated */
	if (!(thisBits & CHARGENMASK))
	{
	    outData.key.keyCode = key;
	    outData.key.origCharSet = outData.key.charSet =
	    outData.key.charCode = outData.key.repeat =
	    outData.key.origCharCode = 0;	/* plan 729 (D024, D164) */
	    LLEventPost(NX_FLAGSCHANGED,evg->cursorLoc,&outData);
	}
    }
}

